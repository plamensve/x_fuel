from __future__ import annotations

import json

from openai import OpenAI

import automation.generate_daily_article_bg as base


def generate_article(facts: dict) -> dict:
    client = OpenAI(api_key=base.require_env("OPENAI_API_KEY"))
    schema = {
        "type": "object",
        "properties": {
            "title": {"type": "string"},
            "description": {"type": "string"},
            "deck": {"type": "string"},
            "body_html": {"type": "string"},
            "sources": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "name": {"type": "string"},
                        "url": {"type": "string"},
                        "published_at": {"type": "string"},
                    },
                    "required": ["name", "url", "published_at"],
                    "additionalProperties": False,
                },
            },
        },
        "required": ["title", "description", "deck", "body_html", "sources"],
        "additionalProperties": False,
    }

    source_list = ", ".join(base.PREFERRED_BG_SOURCES)
    prompt = f"""
Ти си старши икономически редактор на goriva.online. Напиши подробен, полезен и SEO-оптимизиран дневен обзор на БЪЛГАРСКИ език за цените на горивата.

ЦЕЛ НА СТАТИЯТА:
- Да бъде полезна за реални потребители, които търсят актуални цени на бензин, дизел и LPG по градове.
- Да бъде естествено SEO оптимизирана, без keyword stuffing.
- При достатъчно данни целевата дължина е 1500–2500 думи. Не раздувай текста с празни фрази; ако материалът е по-малко, бъди по-кратък.

ЗАГЛАВИЕ:
1. НЕ използвай фрази като „наблюдаваната извадка“, „извадката на goriva.online“ или сходни технически формулировки в заглавието.
2. Заглавието трябва да започва естествено с „Цени на горивата днес“ или „Цени на бензин, дизел и газ днес“.
3. Заглавието трябва да включва София и/или големите градове и да е ясно, конкретно и подходящо за Google Search.
4. Не прави недоказани национални твърдения за поскъпване или поевтиняване.

ЗАДЪЛЖИТЕЛНА СТРУКТУРА:
- кратък lead с най-важното за деня;
- <h2>Цени на горивата днес</h2>;
- <h2>Цени на горивата в София</h2>;
- <h2>Цени на горивата в Пловдив</h2>;
- <h2>Цени на горивата във Варна</h2>;
- <h2>Цени на горивата в Бургас</h2>;
- <h2>Цени на горивата в Русе</h2>;
- <h2>Цени на горивата в Стара Загора</h2>;
- сравнение между големите градове;
- промени спрямо предходен ден, само ако има надеждни сравними данни;
- <h2>Пазарен контекст от български източници</h2>, когато има релевантни новини;
- <h2>Какво да следим</h2>.

ДАННИ И ЧИСЛА:
1. Всички цени и локални числови твърдения идват САМО от FACTS_JSON. Не смятай сам.
2. Когато има display поле, използвай него. Всички цени за читателя са с точно два знака след десетичната запетая.
3. Не е необходимо във всеки абзац да повтаряш, че данните са „извадка“. Достатъчно е веднъж в началото или в методологичната бележка да уточниш, че данните са агрегирани от наличните наблюдения на goriva.online и не са официална държавна статистика.
4. Не повтаряй едни и същи числа механично в няколко секции.

ИЗТОЧНИЦИ И ПАЗАРЕН КОНТЕКСТ:
1. Използвай web search само към български медии, институции и надеждни български бизнес източници. Предпочитани домейни: {source_list}.
2. Търси няколко различни релевантни публикации. При наличие на достатъчно качествени материали върни 4–8 различни източника.
3. Допустими са теми като петрол, доставки, рафинерии, акцизи, данъци, международни пазари, логистика, регулации, търсене и предлагане, когато са пряко релевантни.
4. Не слагай URL или inline citation в body_html. Всички линкове са само в sources и ще се изведат в края на статията.
5. В пазарния контекст не цитирай външни десетични котировки или проценти; описвай външния контекст качествено, за да не се смесва с локалните ценови данни.
6. Не твърди причинно-следствена връзка между конкретна новина и конкретна локална цена без доказателство.

СТИЛ:
- професионален български бизнес/новинарски стил;
- кратки и средни абзаци, ясни подзаглавия;
- без AI клишета, без сензационализъм, без кухи заключения;
- обяснявай практическото значение на разликите за шофьорите;
- използвай естествено фразите „цени на горивата“, „цени на горивата в София“, „бензин“, „дизел“, „газ“/„LPG“ и имената на големите градове;
- body_html може да съдържа само <h2>, <h3>, <p>, <ul>, <li>, <strong>, <blockquote>.

FACTS_JSON:
{json.dumps(facts, ensure_ascii=False, indent=2)}
""".strip()

    response = client.responses.create(
        model=base.MODEL,
        reasoning={"effort": "low"},
        tools=[{"type": "web_search"}],
        input=prompt,
        text={
            "format": {
                "type": "json_schema",
                "name": "daily_fuel_article_longform_bg",
                "strict": True,
                "schema": schema,
            }
        },
    )
    raw = base.response_text(response)
    if not raw:
        raise RuntimeError("OpenAI returned no article text")
    return json.loads(raw)
